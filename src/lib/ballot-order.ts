// Per-link variant order: removes first-position bias while keeping each link's order stable
// across reloads without storing anything. Pure and runtime-agnostic (runs in workerd).

/** 32-bit FNV-1a hash of the string's UTF-16 code units. */
function fnv1a(value: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < value.length; i++) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/** mulberry32: small seeded PRNG returning floats in [0, 1). */
function mulberry32(seed: number): () => number {
  let state = seed;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Deterministic Fisher–Yates shuffle seeded from the token. Returns a new array; never mutates `items`. */
export function orderForToken<T>(items: readonly T[], token: string): T[] {
  const result = [...items];
  const random = mulberry32(fnv1a(token));
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
